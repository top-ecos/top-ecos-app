CREATE VIEW public.user_daily_cumulative_progress AS
 WITH user_activity_bounds AS (
         SELECT mock_results.user_id,
            min((mock_results.created_at)::date) AS first_activity_date,
            max((mock_results.created_at)::date) AS last_activity_date
           FROM public.mock_results
          GROUP BY mock_results.user_id
        ), full_date_series AS (
         SELECT user_activity_bounds.user_id,
            (generate_series((user_activity_bounds.first_activity_date)::timestamp with time zone, (CURRENT_DATE)::timestamp with time zone, '1 day'::interval))::date AS full_date
           FROM user_activity_bounds
        ), daily_averages AS (
         SELECT mock_results.user_id,
            (mock_results.created_at)::date AS activity_date,
            avg(mock_results.score) AS daily_avg_score
           FROM public.mock_results
          GROUP BY mock_results.user_id, ((mock_results.created_at)::date)
        ), combined_data AS (
         SELECT fds.user_id,
            fds.full_date,
            da.daily_avg_score
           FROM (full_date_series fds
             LEFT JOIN daily_averages da ON (((fds.user_id = da.user_id) AND (fds.full_date = da.activity_date))))
        )
 SELECT combined_data.user_id,
    combined_data.full_date,
    avg(combined_data.daily_avg_score) OVER (PARTITION BY combined_data.user_id ORDER BY combined_data.full_date) AS cumulative_average_score
   FROM combined_data;


