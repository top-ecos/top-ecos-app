CREATE VIEW public.user_training_streaks AS
 WITH user_daily_activity AS (
         SELECT DISTINCT mock_results.user_id,
            (mock_results.created_at)::date AS activity_date
           FROM public.mock_results
        ), date_groups AS (
         SELECT user_daily_activity.user_id,
            user_daily_activity.activity_date,
            (user_daily_activity.activity_date - (row_number() OVER (PARTITION BY user_daily_activity.user_id ORDER BY user_daily_activity.activity_date))::integer) AS date_group
           FROM user_daily_activity
        ), streak_lengths AS (
         SELECT date_groups.user_id,
            count(*) AS streak_length,
            max(date_groups.activity_date) AS streak_end
           FROM date_groups
          GROUP BY date_groups.user_id, date_groups.date_group
        )
 SELECT s.user_id,
        CASE
            WHEN (s.streak_end >= (CURRENT_DATE - '1 day'::interval)) THEN s.streak_length
            ELSE (0)::bigint
        END AS current_streak_days
   FROM streak_lengths s
  WHERE (s.streak_end = ( SELECT max(streak_lengths.streak_end) AS max
           FROM streak_lengths
          WHERE (streak_lengths.user_id = s.user_id)));


