-- Name: prevent_direct_token_updates(); Type: FUNCTION; Schema: public; Owner: postgres
--

CREATE FUNCTION public.prevent_direct_token_updates() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
BEGIN
  -- Allow service role to update tokens (Edge Functions with service key bypass RLS anyway)
  IF auth.role() = 'service_role' THEN
    RETURN NEW;
  END IF;

  -- For authenticated users, preserve the old tokens value if they try to change it
  IF auth.role() = 'authenticated' AND OLD.tokens IS DISTINCT FROM NEW.tokens THEN
    NEW.tokens = OLD.tokens;
