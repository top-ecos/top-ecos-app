--
-- Name: get_user_station_rank(text, uuid); Type: FUNCTION; Schema: public; Owner: postgres
--

CREATE FUNCTION public.get_user_station_rank(p_station_id text, p_user_id uuid) RETURNS text
    LANGUAGE plpgsql
    AS $$
DECLARE
    total_users BIGINT;
    user_rank BIGINT;
    latest_user_score NUMERIC;
    percentile_rank NUMERIC;
BEGIN
    -- 1. Get the most recent score for the specified user on the station.
    -- This ensures we rank their latest attempt.
    SELECT score INTO latest_user_score
    FROM public.mock_results
    WHERE station_id = p_station_id AND user_id = p_user_id
    ORDER BY created_at DESC
    LIMIT 1;

    -- If the user has no score for this station, we can't rank them.
    IF latest_user_score IS NULL THEN
        RETURN NULL;
    END IF;

    -- 2. Count the total number of unique users who have taken this station.
    SELECT COUNT(DISTINCT user_id) INTO total_users
    FROM public.mock_results
    WHERE station_id = p_station_id;

    -- 3. If the sample size is too small, don't provide a ranking.
    IF total_users < 5 THEN
        RETURN 'Pas encore de classement';
    END IF;

    -- 4. Find the user's rank by counting how many unique users have a HIGHER
    -- most recent score than them. We add 1 to get the actual rank.
    SELECT COUNT(*) + 1 INTO user_rank
    FROM (
        -- This subquery ensures we only consider the BEST score for each user
        -- to prevent a single user from occupying multiple ranking spots.
        SELECT DISTINCT ON (user_id) user_id, score
        FROM public.mock_results
        WHERE station_id = p_station_id
        ORDER BY user_id, score DESC
    ) as latest_scores
    WHERE score > latest_user_score;

    -- 5. Calculate the percentile and format the output string.
    percentile_rank := (user_rank::NUMERIC / total_users::NUMERIC) * 100;

    RETURN 'Top ' || CEIL(percentile_rank) || '% des étudiants';
END;
$$;


